#!/usr/bin/env ruby

require "csv"
require "json"

root = File.expand_path(__dir__)
sources = %w[korean_benchmark_inventory.csv english_benchmark_inventory.csv]
categories_by_name = {}
current_category = "기타"
File.foreach(File.join(root, "README.md"), encoding: "utf-8") do |line|
  current_category = line.delete_prefix("### ").strip if line.start_with?("### ")
  match = line.match(/^\| \[([^\]]+)\]\([^)]+\) \|/)
  categories_by_name[match[1]] = current_category if match
end

rows = sources.flat_map do |source|
  CSV.read(
    File.join(root, source),
    headers: true,
    encoding: "bom|utf-8",
    liberal_parsing: true
  ).map do |row|
    record = row.to_h
    record["트랙"] = source.start_with?("korean") ? "ko" : "en"
    record["분류"] = categories_by_name.fetch(record["이름"], "기타")
    record
  end
end

recommended_path = File.join(root, "benchmark_top_models.csv")
if File.file?(recommended_path)
  recommended = CSV.read(recommended_path, headers: true, encoding: "bom|utf-8", liberal_parsing: true)
  by_benchmark = recommended.map(&:to_h).group_by { |row| row["benchmark_id"] }
  rows.each do |record|
    entries = by_benchmark[record["id"]]
    next if entries.nil? || entries.empty?
    head = entries.first
    to_entry = lambda do |row|
      score = row["score"].to_s.strip
      {
        "rank" => row["rank"].to_i,
        "model" => row["model"],
        "model_url" => row["model_url"].to_s.strip.empty? ? nil : row["model_url"],
        "score" => score.match?(/\A-?\d+(\.\d+)?\z/) ? score.to_f : score,
        "open_weight" => { "True" => true, "true" => true, "False" => false, "false" => false }[row["open_weight"].to_s]
      }
    end
    record["추천 모델"] = {
      "status" => head["status"],
      "metric" => head["metric"],
      "setting" => head["setting"],
      "source_type" => head["source_type"],
      "source_title" => head["source_title"],
      "source_url" => head["source_url"],
      "source_date" => head["source_date"],
      "accessed" => head["accessed"],
      "all" => entries.each_with_index.select { |row, _| row["scope"] == "all" }.sort_by { |row, index| [row["rank"].to_i, index] }.map { |row, _| to_entry.call(row) },
      "open_weight" => entries.each_with_index.select { |row, _| row["scope"] == "open_weight" }.sort_by { |row, index| [row["rank"].to_i, index] }.map { |row, _| to_entry.call(row) }
    }
    ow_head = entries.find { |row| row["scope"] == "open_weight" && !row["ow_source_url"].to_s.strip.empty? }
    if ow_head
      record["추천 모델"]["open_weight_source"] = {
        "source_type" => ow_head["ow_source_type"],
        "source_title" => ow_head["ow_source_title"],
        "source_url" => ow_head["ow_source_url"],
        "source_date" => ow_head["ow_source_date"],
        "setting" => ow_head["ow_setting"],
        "metric" => ow_head["ow_metric"]
      }
    end
  end
end

output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.BENCHMARK_INVENTORY = #{JSON.generate(rows)};
JAVASCRIPT

File.write(File.join(root, "inventory-data.js"), output)

serving_rows = CSV.read(
  File.join(root, "serving_inventory.csv"),
  headers: true,
  encoding: "bom|utf-8",
  liberal_parsing: true
).map(&:to_h)

serving_output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.SERVING_INVENTORY = #{JSON.generate(serving_rows)};
JAVASCRIPT

meta = {
  benchmark_checked_at: "2026-09-26",
  serving_checked_at: serving_rows.map { |row| row["최근 확인일"] }.compact.max,
  korean_count: rows.count { |row| row["트랙"] == "ko" },
  english_count: rows.count { |row| row["트랙"] == "en" },
  serving_count: serving_rows.length
}

meta_output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.INVENTORY_META = #{JSON.generate(meta)};
JAVASCRIPT

File.write(File.join(root, "serving-data.js"), serving_output)
File.write(File.join(root, "site-meta.js"), meta_output)
puts "Generated site data with #{rows.length} benchmark and #{serving_rows.length} serving records."
