#!/usr/bin/env ruby

require "csv"
require "json"

root = File.expand_path(__dir__)
sources = %w[korean_benchmark_inventory.csv english_benchmark_inventory.csv]
categories_by_name = {}
current_category = "기타"
File.foreach(File.join(root, "README.md"), encoding: "utf-8") do |line|
  current_category = line.delete_prefix("### ").strip if line.start_with?("### ")
  match = line.match(/^\| \[([^\]]+)\]\([^)]+\) \|/)
  categories_by_name[match[1]] = current_category if match
end

rows = sources.flat_map do |source|
  CSV.read(
    File.join(root, source),
    headers: true,
    encoding: "bom|utf-8",
    liberal_parsing: true
  ).map do |row|
    record = row.to_h
    record["트랙"] = source.start_with?("korean") ? "ko" : "en"
    record["분류"] = categories_by_name.fetch(record["이름"], "기타")
    record
  end
end

output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.BENCHMARK_INVENTORY = #{JSON.generate(rows)};
JAVASCRIPT

File.write(File.join(root, "inventory-data.js"), output)

serving_rows = CSV.read(
  File.join(root, "serving_inventory.csv"),
  headers: true,
  encoding: "bom|utf-8",
  liberal_parsing: true
).map(&:to_h)

serving_output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.SERVING_INVENTORY = #{JSON.generate(serving_rows)};
JAVASCRIPT

meta = {
  benchmark_checked_at: "2026-07-28",
  serving_checked_at: serving_rows.map { |row| row["최근 확인일"] }.compact.max,
  korean_count: rows.count { |row| row["트랙"] == "ko" },
  english_count: rows.count { |row| row["트랙"] == "en" },
  serving_count: serving_rows.length
}

meta_output = <<~JAVASCRIPT
  // Generated by build_site_data.rb. Do not edit directly.
  window.INVENTORY_META = #{JSON.generate(meta)};
JAVASCRIPT

File.write(File.join(root, "serving-data.js"), serving_output)
File.write(File.join(root, "site-meta.js"), meta_output)
puts "Generated site data with #{rows.length} benchmark and #{serving_rows.length} serving records."
