#!/usr/bin/env python3
"""Generate inventory-data.js, serving-data.js and site-meta.js from the CSV sources.

Standard library only. Output is deterministic: rows keep CSV order and ties keep
their input order.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = ["korean_benchmark_inventory.csv", "english_benchmark_inventory.csv"]
BENCHMARK_CHECKED_AT = "2026-09-26"
HEADER = "// Generated by build_site_data.py. Do not edit directly.\n"
NUMBER = re.compile(r"\A-?\d+(\.\d+)?\Z")


def read_csv(name: str) -> list[dict]:
    """Read a CSV with an optional BOM; empty cells become None (matching the JSON null)."""
    with (ROOT / name).open(encoding="utf-8-sig", newline="") as fh:
        return [{key: (value if value != "" else None) for key, value in row.items()} for row in csv.DictReader(fh)]


def to_json(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def categories_from_readme() -> dict[str, str]:
    categories: dict[str, str] = {}
    current = "기타"
    for line in (ROOT / "README.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("### "):
            current = line[4:].strip()
        match = re.match(r"^\| \[([^\]]+)\]\([^)]+\) \|", line)
        if match:
            categories[match.group(1)] = current
    return categories


def recommended_entry(row: dict) -> dict:
    score = (row.get("score") or "").strip()
    flag = {"True": True, "true": True, "False": False, "false": False}.get(row.get("open_weight") or "")
    return {
        "rank": int(row.get("rank") or 0),
        "model": row.get("model"),
        "model_url": row.get("model_url") or None,
        "score": float(score) if NUMBER.match(score) else score,
        "open_weight": flag,
    }


def attach_recommended(rows: list[dict]) -> None:
    path = ROOT / "benchmark_top_models.csv"
    if not path.is_file():
        return
    by_benchmark: dict[str, list[dict]] = {}
    for row in read_csv(path.name):
        by_benchmark.setdefault(row["benchmark_id"], []).append(row)
    for record in rows:
        entries = by_benchmark.get(record["id"])
        if not entries:
            continue
        head = entries[0]
        indexed = list(enumerate(entries))

        def ranked(scope: str) -> list[dict]:
            chosen = [(index, row) for index, row in indexed if row.get("scope") == scope]
            chosen.sort(key=lambda pair: (int(pair[1].get("rank") or 0), pair[0]))
            return [recommended_entry(row) for _, row in chosen]

        record["추천 모델"] = {
            "status": head.get("status"),
            "metric": head.get("metric"),
            "setting": head.get("setting"),
            "source_type": head.get("source_type"),
            "source_title": head.get("source_title"),
            "source_url": head.get("source_url"),
            "source_date": head.get("source_date"),
            "accessed": head.get("accessed"),
            "all": ranked("all"),
            "open_weight": ranked("open_weight"),
        }
        ow_head = next((row for row in entries if row.get("scope") == "open_weight" and (row.get("ow_source_url") or "").strip()), None)
        if ow_head:
            record["추천 모델"]["open_weight_source"] = {
                "source_type": ow_head.get("ow_source_type"),
                "source_title": ow_head.get("ow_source_title"),
                "source_url": ow_head.get("ow_source_url"),
                "source_date": ow_head.get("ow_source_date"),
                "setting": ow_head.get("ow_setting"),
                "metric": ow_head.get("ow_metric"),
            }


def serving_entry(row: dict) -> dict:
    value = (row.get("value") or "").strip()
    per_acc = (row.get("per_accelerator") or "").strip()
    return {
        "rank": int(row.get("rank") or 0),
        "label": row.get("label"),
        "label_url": row.get("label_url") or None,
        "model": row.get("model"),
        "hardware": row.get("hardware"),
        "engine": row.get("engine"),
        "condition": row.get("condition"),
        "value": float(value) if NUMBER.match(value) else value,
        "unit": row.get("unit"),
        "per_accelerator": float(per_acc) if NUMBER.match(per_acc) else (per_acc or None),
    }


def attach_serving_reference(rows: list[dict]) -> None:
    path = ROOT / "serving_reference_values.csv"
    if not path.is_file():
        return
    by_board: dict[str, list[dict]] = {}
    for row in read_csv(path.name):
        by_board.setdefault(row["serving_id"], []).append(row)
    for record in rows:
        entries = by_board.get(record["id"])
        if not entries:
            continue
        head = entries[0]
        ordered = sorted(enumerate(entries), key=lambda pair: (int(pair[1].get("rank") or 0), pair[0]))
        record["대표 측정값"] = {
            "status": head.get("status"),
            "model": head.get("model"),
            "scenario": head.get("scenario"),
            "metric": head.get("metric"),
            "unit": head.get("unit"),
            "direction": head.get("direction"),
            "board_condition": head.get("board_condition"),
            "source_type": head.get("source_type"),
            "source_title": head.get("source_title"),
            "source_url": head.get("source_url"),
            "source_date": head.get("source_date"),
            "caveat": head.get("caveat"),
            "accessed": head.get("accessed"),
            "rows": [serving_entry(row) for _, row in ordered],
        }


def main() -> None:
    categories = categories_from_readme()
    rows: list[dict] = []
    for source in SOURCES:
        track = "ko" if source.startswith("korean") else "en"
        for record in read_csv(source):
            record["트랙"] = track
            record["분류"] = categories.get(record["이름"], "기타")
            rows.append(record)
    attach_recommended(rows)

    serving_rows = read_csv("serving_inventory.csv")
    attach_serving_reference(serving_rows)
    meta = {
        "benchmark_checked_at": BENCHMARK_CHECKED_AT,
        "serving_checked_at": max((row["최근 확인일"] for row in serving_rows if row.get("최근 확인일")), default=None),
        "korean_count": sum(1 for row in rows if row["트랙"] == "ko"),
        "english_count": sum(1 for row in rows if row["트랙"] == "en"),
        "serving_count": len(serving_rows),
    }

    (ROOT / "inventory-data.js").write_text(f"{HEADER}window.BENCHMARK_INVENTORY = {to_json(rows)};\n", encoding="utf-8")
    (ROOT / "serving-data.js").write_text(f"{HEADER}window.SERVING_INVENTORY = {to_json(serving_rows)};\n", encoding="utf-8")
    (ROOT / "site-meta.js").write_text(f"{HEADER}window.INVENTORY_META = {to_json(meta)};\n", encoding="utf-8")
    print(f"Generated site data with {len(rows)} benchmark and {len(serving_rows)} serving records.")


if __name__ == "__main__":
    main()
